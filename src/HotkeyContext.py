"""A_ThisHotkey, A_PriorHotkey, A_PriorKey, A_TimeSinceThisHotkey, A_TimeSincePriorHotkey and the A_TimeIdle
family, fed by the hotkey hook and its dispatcher."""

from __future__ import annotations

import ctypes
import threading
from collections import deque
from ctypes import wintypes
from dataclasses import dataclass

from yorha import Win32Api as api

KEY_HISTORY_SIZE = 40
# A_TimeSince* when there is no such hotkey; AHK v2 leaves them blank
NO_HOTKEY_TIME = -1


@dataclass(frozen=True)
class _Fired:
    name: str
    tick: int


class _LastInputInfo(ctypes.Structure):
    _fields_ = [("cbSize", wintypes.UINT), ("dwTime", wintypes.DWORD)]


_lock = threading.Lock()
_global = {"this": None, "prior": None}
_local = threading.local()
# (key name, up) of every keyboard and mouse button event not generated by an AHK-style sender, newest last
_history: deque[tuple[str, bool]] = deque(maxlen=KEY_HISTORY_SIZE)
# GetTickCount of the last physical event each hook saw; 0 while that hook is not installed
_physicalTicks = {"keyboard": 0, "mouse": 0}


def _Tick() -> int:
    return api.GetTickCount()


def _Since(tick: int) -> int:
    return (_Tick() - tick) & 0xFFFFFFFF


# ---- fed by the hook and the dispatcher ----


def HotkeyStarted(name: str, pressedTick: int) -> None:
    """The dispatcher is about to run hotkey `name`, pressed at `pressedTick`: it becomes A_ThisHotkey on every
    thread, and stays so on this one for the callback even if another hotkey fires meanwhile."""
    fired = _Fired(name, pressedTick)
    with _lock:
        _global["prior"] = _global["this"]
        _global["this"] = fired
        _local.context = (_global["this"], _global["prior"])


def HotkeyFinished() -> None:
    _local.context = None


def RecordKey(name: str, up: bool) -> None:
    with _lock:
        _history.append((name, up))


def RecordPhysical(device: str) -> None:
    _physicalTicks[device] = _Tick()


def HookInstalled(device: str, installed: bool) -> None:
    _physicalTicks[device] = _Tick() if installed else 0


# ---- the built-in variables ----


def _Context() -> tuple[_Fired | None, _Fired | None]:
    context = getattr(_local, "context", None)
    if context is not None:
        return context
    with _lock:
        return _global["this"], _global["prior"]


def ThisHotkey() -> str:
    """A_ThisHotkey: the hotkey's name as registered; "" before any hotkey fired."""
    fired = _Context()[0]
    return "" if (fired is None) else fired.name


def PriorHotkey() -> str:
    fired = _Context()[1]
    return "" if (fired is None) else fired.name


def TimeSinceThisHotkey() -> int:
    """Milliseconds since A_ThisHotkey was pressed; -1 when there is none."""
    fired = _Context()[0]
    return NO_HOTKEY_TIME if (fired is None) else _Since(fired.tick)


def TimeSincePriorHotkey() -> int:
    fired = _Context()[1]
    return NO_HOTKEY_TIME if (fired is None) else _Since(fired.tick)


def PriorKey() -> str:
    """A_PriorKey: the last key pressed before the most recent key press or release ("" when none). Needs the
    hotkey hook; AHK-generated input does not count."""
    with _lock:
        events = list(_history)
    for name, up in reversed(events[:-1]):
        if not up:
            return name
    return ""


def TimeIdle() -> int:
    """A_TimeIdle: milliseconds since the system last got any input, generated input included."""
    info = _LastInputInfo(ctypes.sizeof(_LastInputInfo), 0)
    if not api.GetLastInputInfo(ctypes.byref(info)):
        return 0
    return _Since(info.dwTime)


def _IdleOf(device: str) -> int:
    tick = _physicalTicks[device]
    return TimeIdle() if (tick == 0) else _Since(tick)


def TimeIdleKeyboard() -> int:
    """Physical keyboard idle time while the keyboard hook runs, else A_TimeIdle."""
    return _IdleOf("keyboard")


def TimeIdleMouse() -> int:
    """Physical mouse idle time while the mouse hook runs, else A_TimeIdle."""
    return _IdleOf("mouse")


def TimeIdlePhysical() -> int:
    """A_TimeIdlePhysical: ignores generated input of each device whose hook runs."""
    return min(TimeIdleKeyboard(), TimeIdleMouse())
